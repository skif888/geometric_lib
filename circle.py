import math
"""
Модуль для работы с квадратом.
Содержит функции вычисления площади и периметра квадрата.
"""

def area(r):
    """
    Вычисляет площадь круга.

    Пример:
        area(5)
    """
    return math.pi * r * r

def perimeter(r):
    """
    Вычисляет длину окружности.

    Пример:
        perimeter(5)
    """
    return 2 * math.pi * r

